import { cp, mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const desktopRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const resourcesRoot = path.join(desktopRoot, "src-tauri", "resources");
const runtimeRoot = path.join(resourcesRoot, "runtime");
const agentRoot = path.join(resourcesRoot, "agent");
const browsersRoot = path.join(resourcesRoot, "browsers");
const adapterPublicKeySource = path.join(desktopRoot, "resources", "adapter_ed25519_public.pem");
const adapterPublicKeyTarget = path.join(resourcesRoot, "adapter_ed25519_public.pem");
const require = createRequire(import.meta.url);

async function copyPackage(name) {
  const packageJson = require.resolve(`${name}/package.json`, { paths: [desktopRoot] });
  await cp(path.dirname(packageJson), path.join(agentRoot, "node_modules", name), { recursive: true });
}

await rm(resourcesRoot, { recursive: true, force: true });
await mkdir(runtimeRoot, { recursive: true });
await mkdir(agentRoot, { recursive: true });
await mkdir(browsersRoot, { recursive: true });

const runtimeName = process.platform === "win32" ? "node.exe" : "node";
await cp(process.execPath, path.join(runtimeRoot, runtimeName));
await cp(path.join(desktopRoot, "src"), path.join(agentRoot, "src"), { recursive: true });
await cp(adapterPublicKeySource, adapterPublicKeyTarget);
const desktopPackageMetadata = JSON.parse(await readFile(path.join(desktopRoot, "package.json"), "utf8"));
if (typeof desktopPackageMetadata.version !== "string" || !desktopPackageMetadata.version.trim()) {
  throw new Error("DESKTOP_PACKAGE_VERSION_MISSING");
}
await writeFile(
  path.join(agentRoot, "package.json"),
  JSON.stringify({ type: "module", private: true, version: desktopPackageMetadata.version.trim() }, null, 2),
  "utf8"
);
await copyPackage("playwright");
await copyPackage("playwright-core");

const { chromium } = await import("playwright");
const chromiumExecutable = chromium.executablePath();
const chromiumBundle = path.dirname(path.dirname(chromiumExecutable));
const browserCacheRoot = path.dirname(chromiumBundle);
const chromiumRevision = path.basename(chromiumBundle).replace(/^chromium-/, "");
const requiredBrowserBundles = [
  `chromium-${chromiumRevision}`,
  `chromium_headless_shell-${chromiumRevision}`,
];
const availableBrowserBundles = new Set(await readdir(browserCacheRoot));
for (const bundleName of requiredBrowserBundles) {
  if (!availableBrowserBundles.has(bundleName)) {
    throw new Error(`Missing Playwright browser bundle ${bundleName}. Run npm run install-browsers first.`);
  }
  await cp(path.join(browserCacheRoot, bundleName), path.join(browsersRoot, bundleName), { recursive: true });
}
await writeFile(path.join(runtimeRoot, "README.txt"), "Generated by npm run prepare:tauri-resources.\n", "utf8");
await writeFile(path.join(agentRoot, "README.txt"), "Generated by npm run prepare:tauri-resources.\n", "utf8");
await writeFile(path.join(browsersRoot, "README.txt"), "Generated by npm run prepare:tauri-resources.\n", "utf8");

console.log(`Prepared Tauri runtime resources at ${resourcesRoot}`);
