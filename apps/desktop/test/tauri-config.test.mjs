  assert.match(updateManifest.version, /^\d+\.\d+\.\d+$/);
  assert.match(updateManifest.sha256, /^[a-f0-9]{64}$/);
  assert.ok(Array.isArray(updateManifest.notes));
  assert.ok(updateManifest.notes.length > 0);

  assert.match(mainRs, /fn app_version\(\) -> String/);
  assert.match(mainRs, /CARGO_PKG_VERSION/);
  assert.match(mainRs, /generate_handler!\[[\s\S]*app_version[\s\S]*\]/);

  assert.match(html, /desktop-version\.json/);
  assert.match(html, /UPDATE_MANIFEST_URLS/);
  assert.match(html, /http:\/\/192\.0\.2\.10\/downloads\/desktop-version\.json/);
  assert.match(html, /fetchDesktopRelease/);
